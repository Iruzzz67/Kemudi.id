// Deterministic environment contract checks without WebGL or a running server.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const THREE = require('../../src/Kemudi.Web/wwwroot/simulation-3d/vendor/three.min.js');
const context = { THREE, window: {} };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../../src/Kemudi.Web/wwwroot/simulation-3d/systems/environment-system.js'), 'utf8'), context);
const { EnvironmentSystem } = context.window;
const scene = new THREE.Scene();
scene.background = new THREE.Color(0xb9d2df);
scene.fog = new THREE.Fog(0xb9d2df, 85, 300);
scene.environment = new THREE.Texture();
const originalBackground = scene.background;
const originalFog = scene.fog;
const originalEnvironment = scene.environment;
const ambient = new THREE.AmbientLight(0xffffff, .5);
const sun = new THREE.DirectionalLight(0xffffff, .8);
sun.name = 'DrivingSun'; sun.position.set(50, 80, 30);
const hemi = new THREE.HemisphereLight(0x87ceeb, 0x3a7d44, .3);
scene.add(ambient, sun, sun.target, hemi);
const roadMaterial = new THREE.MeshStandardMaterial({ color: 0x35434b, roughness: .9 });
const road = new THREE.Mesh(new THREE.PlaneGeometry(7, 30), roadMaterial);
road.name = 'asphalt';
const wall = new THREE.Mesh(new THREE.BoxGeometry(), roadMaterial);
wall.name = 'house';
const lampMaterial = new THREE.MeshLambertMaterial({ color: 0xe7e2cb });
const lamp = new THREE.Mesh(new THREE.BoxGeometry(), lampMaterial);
lamp.name = 'street-lamp';
scene.add(road, wall, lamp);
const renderer = { toneMappingExposure: 1.15 };
const camera = new THREE.PerspectiveCamera();
camera.position.set(0, 1.6, 0);
const env = new EnvironmentSystem(scene, renderer, { seed: 7 });
assert.equal(scene.children.filter(o => o.isAmbientLight).length, 1, 'reuse ambient light');
assert.equal(scene.children.filter(o => o.isDirectionalLight).length, 1, 'reuse sun');
assert.equal(wall.material, roadMaterial, 'non-road shared material untouched');
assert.notEqual(road.material, roadMaterial, 'road owns a clone');
const colors = new Set();
for (const time of ['pagi', 'siang', 'sore', 'malam']) {
  env.setTimeOfDay(time);
  for (const weather of ['off', 'light', 'heavy']) {
    env.setWeather(weather);
    env.update(1 / 60, camera);
    const state = env.getState();
    assert.equal(state.timeOfDay, time);
    assert.equal(state.weather, weather);
    assert.equal(state.night, time === 'malam');
    assert.ok(state.roadGripFactor > 0 && state.roadGripFactor <= 1);
    assert.ok(state.visibilityFactor > 0 && state.visibilityFactor <= 1);
    assert.ok(state.recommendedAIMaxSpeedFactor > 0 && state.recommendedAIMaxSpeedFactor <= 1);
    assert.equal(env.rain.visible, weather !== 'off');
    assert.equal(env.rain.geometry.drawRange.count, weather === 'off' ? 0 : weather === 'light' ? 1200 : 3200);
    assert.ok(scene.fog.far > scene.fog.near);
    assert.ok(Number.isFinite(renderer.toneMappingExposure));
    assert.ok(env.streetLights.length <= 4);
    console.log('PASS', time, weather);
  }
  colors.add(scene.background.getHexString());
}
assert.equal(colors.size, 4, 'all time presets visibly distinct');
env.setTimeOfDay('pagi');
env.update(1 / 60, camera);
const direction = sun.position.clone().sub(sun.target.position).normalize();
camera.position.y = 48;
env.update(1 / 60, camera);
assert.ok(direction.distanceTo(sun.position.clone().sub(sun.target.position).normalize()) < 1e-8, 'camera height must not change sunlight direction');
camera.position.y = 1.6;
env.setTimeOfDay('siang'); env.setWeather('off');
assert.equal(road.material.roughness, .9);
const dry = road.material.color.clone();
env.setWeather('heavy');
assert.ok(road.material.roughness < .9);
assert.ok(road.material.color.r < dry.r);
assert.equal(wall.material, roadMaterial);
assert.equal(wall.material.roughness, .9);
env.setTimeOfDay('malam');
assert.ok(lamp.material.emissiveIntensity > 0);
const previousState = env.getState();
assert.equal(env.setTimeOfDay('invalid'), false);
assert.equal(env.setWeather('snow'), false);
assert.equal(env.getState(), previousState, 'invalid presets preserve state');
const positions = env.rain.geometry.attributes.position;
const frozen = Array.from(positions.array);
env.update(0, camera, { cockpit: true, vehicleType: 'MOBIL' });
assert.deepEqual(Array.from(positions.array), frozen, 'pause freezes every drop');
const geometry = env.rain.geometry;
const material = env.rain.material;
for (let i = 0; i < 200; i++) env.update(1 / 60, camera, { cockpit: true, vehicleType: 'TRUK' });
assert.equal(env.rain.geometry, geometry, 'rain geometry pooled');
assert.equal(env.rain.material, material, 'rain material pooled');
assert.notDeepEqual(Array.from(positions.array), frozen, 'unpaused rain moves');
for (let i = 0; i < env.rain.geometry.drawRange.count; i += 2) {
  const x = positions.getX(i), z = positions.getZ(i);
  assert.ok(x * x + z * z >= env.cabinExclusionRadius ** 2 - .001, 'rain excluded from enclosed cabin');
}
assert.equal(scene.environment, null, 'night does not keep bright daytime reflection map');
env.setTimeOfDay('siang');
assert.equal(scene.environment, originalEnvironment);
let disposedGeometry = 0, disposedMaterial = 0;
geometry.addEventListener('dispose', () => disposedGeometry++);
material.addEventListener('dispose', () => disposedMaterial++);
env.dispose(); env.dispose();
assert.equal(disposedGeometry, 1);
assert.equal(disposedMaterial, 1);
assert.equal(road.material, roadMaterial);
assert.equal(lamp.material, lampMaterial);
assert.equal(scene.background, originalBackground);
assert.equal(scene.fog, originalFog);
assert.equal(scene.environment, originalEnvironment);
assert.equal(renderer.toneMappingExposure, 1.15);
assert.equal(ambient.intensity, .5);
assert.equal(sun.intensity, .8);
assert.equal(hemi.intensity, .3);
assert.equal(scene.getObjectByName('RealismRain'), undefined);
env.update(1 / 60, camera);
assert.equal(env.setWeather('heavy'), false, 'disposed instance is inert');
const lightScene = new THREE.Scene();
const streetEnvironment = new EnvironmentSystem(lightScene, { toneMappingExposure: 1 }, {
  track: { roadHeight: .09, intersections: [{ definition: { center: new THREE.Vector3(0, .09, -80) } }] },
});
streetEnvironment.setTimeOfDay('malam');
camera.position.set(0, 2, -80);
streetEnvironment.update(1 / 60, camera);
assert.equal(streetEnvironment.streetLights.length, 4);
assert.ok(streetEnvironment.streetLights.every(l => l.visible && l.intensity > 0 && !l.castShadow));
camera.position.set(1000, 2, 1000);
streetEnvironment.update(1 / 60, camera);
assert.ok(streetEnvironment.streetLights.every(l => !l.visible), 'far lamps culled');
streetEnvironment.dispose();
assert.equal(lightScene.children.length, 0, 'owned fallback lights and targets cleaned up');
console.log('PASS wet road isolation, invalid presets, pooled rain, cabin exclusion, pause and idempotent cleanup');
