const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const output = path.resolve(__dirname, '../../artifacts/integrated-ui');
  fs.mkdirSync(output, { recursive: true });
  const checks = [], errors = [];
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' });
  page.on('pageerror', e => errors.push(e.message));
  try {
    const base = process.env.WEB_URL || 'http://127.0.0.1:5260';
    await page.goto(base, { waitUntil: 'networkidle' });
    await page.locator('.hero h1').waitFor();
    const palette = await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--kemudi-bg').trim());
    assert.equal(palette, '#17191c');
    await page.screenshot({ path: path.join(output, 'home.png'), fullPage: true });
    await page.locator('.kemudi-navbar a[href="simulasi"]').click();
    await page.locator('.simulation-frame iframe').waitFor();
    await page.locator('.kemudi-navbar').waitFor();
    const frame = page.frameLocator('.simulation-frame iframe');
    const sim = page.frames().find(f => f.url().includes('/simulation-3d/'));
    await sim.waitForFunction(() => window.kemudiSimulation?.snapshot().phase === 'walking', null, {timeout:60000});
    assert.equal(await frame.locator('#vehicle-select').isVisible(), false);
    assert.equal(new URL(page.url()).pathname, '/simulasi');
    const navbarBox=await page.locator('.kemudi-navbar').boundingBox(), frameBox=await page.locator('iframe').boundingBox();
    assert.ok(Math.abs(frameBox.y-(navbarBox.y+navbarBox.height))<2);
    assert.equal(frameBox.width,1440);
    const simulatorPalette = await frame.locator('html').evaluate(el => getComputedStyle(el).getPropertyValue('--kemudi-bg').trim());
    assert.equal(simulatorPalette, palette);
    checks.push('navbar Simulasi opens the 3D world automatically on the same page, below the navbar at full width');
    await page.screenshot({ path: path.join(output, 'simulation.png'), fullPage: true });
    await frame.locator('#wh-enter').click();
    await sim.waitForFunction(() => window.kemudiSimulation.snapshot().phase === 'driving');
    await frame.locator('#sim-canvas').focus();
    await page.keyboard.press('KeyI');
    await sim.waitForFunction(() => window.kemudiSimulation.snapshot().engine);
    await page.keyboard.press('Space');
    await page.keyboard.down('KeyW');
    await sim.waitForFunction(() => window.kemudiSimulation.snapshot().speed > 1);
    await page.keyboard.up('KeyW');
    await page.keyboard.press('KeyP');
    await sim.waitForFunction(() => window.kemudiSimulation.snapshot().phase === 'paused');
    checks.push('embedded canvas accepts enter, ignition, handbrake, drive and pause keyboard input');
    await frame.locator('#sim-reset').click();
    await frame.locator('#vehicle-select').waitFor({state:'visible'});
    checks.push('vehicle selection remains available on demand');
    await page.locator('.navbar-brand').click();
    await page.locator('.hero h1').waitFor();
    assert.equal(page.frames().length, 1);
    checks.push('return to home unmounts simulator');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(base + '/simulasi/play?vehicle=MOTOR&transmission=manual');
    await page.locator('.simulation-frame iframe').waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.match(await page.locator('iframe').getAttribute('src'), /vehicle=MOTOR&transmission=manual/);
    await page.screenshot({ path: path.join(output, 'simulation-mobile.png'), fullPage: true });
    checks.push('legacy URL retains vehicle/transmission, mobile layout has no horizontal overflow');
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify({ passed: true, checks, errors }, null, 2));
    console.log(checks);
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
